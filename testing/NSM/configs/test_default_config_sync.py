"""
`NSM/configs/default_config.json` is generated by
`NSM/configs/generate_sdf_default_config.py`. Nothing enforced that, so the two drifted:
`axis_align` was commented out of the generator without regenerating, and `eikonal_weight`
was added to the generator and never propagated. Both were inert, but the next drift might
not be.
"""

import json
import os

import pytest

import NSM
from NSM.configs.generate_sdf_default_config import DEFAULT_CONFIG_PATH
from NSM.configs.generate_sdf_default_config import config as generated_config

SHIPPED_PATH = os.path.join(os.path.dirname(NSM.__file__), "configs", "default_config.json")


@pytest.fixture(scope="module")
def shipped_config():
    with open(SHIPPED_PATH) as f:
        return json.load(f)


def test_generator_writes_to_the_shipped_path():
    """A generator that writes somewhere else is how the two drifted in the first place."""
    assert os.path.realpath(DEFAULT_CONFIG_PATH) == os.path.realpath(SHIPPED_PATH)


def test_shipped_config_matches_the_generator(shipped_config):
    # Round-trip the generator through JSON so Python values (None, True) compare against
    # their serialized forms rather than failing on type.
    expected = json.loads(json.dumps(generated_config))

    assert shipped_config == expected, (
        "NSM/configs/default_config.json is out of sync with its generator. "
        "Regenerate with: python -m NSM.configs.generate_sdf_default_config"
    )


def test_importing_the_generator_writes_nothing(tmp_path, monkeypatch):
    """
    The write used to run at import time, into the caller's cwd, so merely importing this
    module littered whatever directory you happened to be in.
    """
    monkeypatch.chdir(tmp_path)

    import importlib

    import NSM.configs.generate_sdf_default_config as module

    importlib.reload(module)

    assert list(tmp_path.iterdir()) == []
